#!/usr/bin/env python3
"""Firmware targets: the one place that says which parts each setup has.

build.yaml (read by GitHub Actions) is generated from this file, local
builds (scripts/build_matrix.py) and flashing (scripts/flash-all.sh) use it
too. To add a setup, a board or an OS, edit MODES / OSES below and run
`scripts/firmware.py gen`.

    scripts/firmware.py gen [--check]           # write build.yaml (--check: fail if outdated)
    scripts/firmware.py list [--mode M] [--os O] [--reset]
                                                # firmware names of a setup, one per line
    scripts/firmware.py modes                   # setup names

Setups (modes):
  dongle     dongle is central and connects to the computer, halves are peripherals
  no-dongle  left half is central and connects to the computer, right half is peripheral

The split role is fixed at build time (Kconfig), so a setup is changed by
flashing, not at runtime. The right half has one firmware for both setups.
"""
import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BUILD_YAML = REPO / "build.yaml"

OSES = ["mac", "linux"]

# central: shield and boards it is built for (built once per OS, ZMK Studio on).
# peripherals: shields of the halves (nice!nano only, one build for both OSes).
MODES = {
    "dongle": {
        "central": ("corne_central_dongle", ["nice_nano//zmk", "xiao_ble//zmk"]),
        "peripherals": ["corne_peripheral_left", "corne_peripheral_right"],
    },
    "no-dongle": {
        "central": ("corne_central_left", ["nice_nano//zmk"]),
        "peripherals": ["corne_peripheral_right"],
    },
}
PERIPHERAL_BOARD = "nice_nano//zmk"
STUDIO_SNIPPET = "studio-rpc-usb-uart"


def default_name(shield, board):
    # Same as the ZMK workflow without artifact-name: <shield>-<board with / -> _>
    return f"{shield}-{board.replace('//', '_').replace('/', '_')}"


def central(shield, board, os):
    return {
        "board": board,
        "shield": shield,
        "snippet": STUDIO_SNIPPET,
        "cmake-args": f"-DDTS_EXTRA_CPPFLAGS=-DOS_{os.upper()}",
        "artifact-name": f"{default_name(shield, board)}-{os}",
    }


def peripheral(shield):
    # Peripherals compile the keymap but never use it; OS_LINUX only
    # satisfies the #error check in config/corne.keymap.
    return {"board": PERIPHERAL_BOARD, "shield": shield,
            "cmake-args": "-DDTS_EXTRA_CPPFLAGS=-DOS_LINUX"}


def name(t):
    return t.get("artifact-name") or default_name(t["shield"], t["board"])


def targets(mode=None, os=None, reset=True):
    """Targets in build order, without duplicates (the right half is shared)."""
    out, seen = [], set()

    def add(t):
        if name(t) not in seen:
            seen.add(name(t))
            out.append(t)

    boards_used = []
    for m in [mode] if mode else MODES:
        shield, boards = MODES[m]["central"]
        for board in boards:
            for o in [os] if os else OSES:
                add(central(shield, board, o))
        for p in MODES[m]["peripherals"]:
            add(peripheral(p))
        boards_used += boards + [PERIPHERAL_BOARD]
    if reset:
        # settings_reset for every board of the setup(s)
        for board in dict.fromkeys(boards_used):
            add({"board": board, "shield": "settings_reset"})
    return out


HEADER = """\
# GENERATED by scripts/firmware.py from MODES / OSES there: edit that file and
# run `scripts/firmware.py gen`. The pre-commit hook and CI check it is current.
#
# Setups: dongle (dongle is central) and no-dongle (left half is central).
# Boards use the Zephyr 4.1 names with the ZMK variant (`<board>//zmk`).
# ZMK Studio runs only on the central, so only centrals get the studio snippet.
# The central processes the keymap, so it is built once per target OS
# (-DOS_MAC / -DOS_LINUX, see "Target OS" in config/corne.keymap) and the
# file name ends with the OS. Peripherals have one build for both systems.
---
include:
"""
KEYS = ["board", "shield", "snippet", "cmake-args", "artifact-name"]


def render():
    lines = [HEADER.rstrip("\n")]
    for t in targets():
        first = True
        for k in KEYS:
            if k in t:
                lines.append(f"  {'- ' if first else '  '}{k}: {t[k]}")
                first = False
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen", help="write build.yaml")
    g.add_argument("--check", action="store_true", help="fail if build.yaml is outdated")
    ls = sub.add_parser("list", help="firmware names of a setup")
    ls.add_argument("--mode", choices=list(MODES))
    ls.add_argument("--os", choices=OSES)
    ls.add_argument("--reset", action="store_true", help="include settings_reset")
    sub.add_parser("modes", help="setup names")
    a = ap.parse_args()

    if a.cmd == "gen":
        text = render()
        if a.check:
            if BUILD_YAML.read_text() != text:
                sys.exit("build.yaml is outdated: run scripts/firmware.py gen")
            return
        BUILD_YAML.write_text(text)
    elif a.cmd == "list":
        for t in targets(a.mode, a.os, a.reset):
            print(name(t))
    elif a.cmd == "modes":
        print("\n".join(MODES))


if __name__ == "__main__":
    main()
